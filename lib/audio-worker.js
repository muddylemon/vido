'use strict';
const { parentPort, workerData } = require('node:worker_threads');
const fs = require('node:fs');
const start = performance.now();
const { renderSoundtrack, toWav } = require(workerData.module);
const audio = renderSoundtrack(48000, workerData.duration);
if (audio.L.length !== Math.round(workerData.duration * 48000) || audio.R.length !== audio.L.length) throw new Error('Unexpected audio length');
for (const channel of [audio.L, audio.R]) for (const sample of channel) if (!Number.isFinite(sample) || Math.abs(sample) > 1) throw new Error('Invalid audio sample');
fs.writeFileSync(workerData.output, Buffer.from(toWav(audio)));
parentPort.postMessage({ elapsedMs: Math.round(performance.now() - start) });
